/**
 * Meta Pixel + Google Ads gtag.js loader snippets, as full <script> tags.
 *
 * Single source of truth for scripts/prerender.js (imported directly, see below) AND for
 * the vitest coverage in src/pages/start/funnel/__tests__/adSnippets.test.ts (which imports
 * these same functions and evals their output in a sandboxed vm context to assert
 * window.fbq / window.gtag actually get assigned and don't throw -- this is the harness that
 * would have caught, and now guards against, a broken base-code stub silently no-oping every
 * pixel/gtag call).
 *
 * index.html carries its own copy of this logic (it has to: Vite's %VITE_X% HTML env
 * replacement only operates on the literal index.html source file, so the snippet bodies
 * can't be generated by importing this module into a static HTML file). Keep both copies
 * behaviorally identical -- see the comment above the snippets in index.html for the id
 * injection difference (data attribute + getAttribute there, vs. JSON.stringify here) and
 * why it exists.
 */

// Meta's official base pixel code, verbatim except for the id substitution. The critical
// line is `n=f.fbq=function(){...}` -- it assigns the stub to BOTH the local `n` (used
// internally by the IIFE) AND `f.fbq` (i.e. `window.fbq`, the public API every fbq() call
// site -- including the two below and analytics.ts's pixel() wrapper -- depends on). Drop
// the `f.fbq=` half and `window.fbq` never gets set: `fbq('init', id)` throws
// ReferenceError, and every future fbq() call silently no-ops forever.
export function buildMetaPixelSnippet(id) {
  if (!id) return "";
  return `<script data-ad-snippet="meta-pixel">
    !function(f,b,e,v,n,t,s)
    {if(f.fbq)return;n=f.fbq=function(){n.callMethod?
    n.callMethod.apply(n,arguments):n.queue.push(arguments)};
    if(!f._fbq)f._fbq=n;n.push=n;n.loaded=!0;n.version='2.0';
    n.queue=[];t=b.createElement(e);t.async=!0;
    t.src=v;s=b.getElementsByTagName(e)[0];
    s.parentNode.insertBefore(t,s)}(window, document,'script',
    'https://connect.facebook.net/en_US/fbevents.js');
    fbq('init', ${JSON.stringify(id)});
    fbq('track', 'PageView');
  </script>`;
}

// Google's gtag.js loader. Loaded via a JS-created <script> element (not a static
// `<script src="...">` tag) so a build with an unset id never fires a broken network
// request -- see index.html's comment for why a static src attribute can't be guarded.
export function buildGtagSnippet(id) {
  if (!id) return "";
  return `<script data-ad-snippet="gtag">
    window.dataLayer = window.dataLayer || [];
    window.gtag = function () { window.dataLayer.push(arguments); };
    (function () {
      var s = document.createElement("script");
      s.async = true;
      s.src = ${JSON.stringify("https://www.googletagmanager.com/gtag/js?id=" + id)};
      document.head.appendChild(s);
    })();
    gtag('js', new Date());
    gtag('config', ${JSON.stringify(id)});
  </script>`;
}
